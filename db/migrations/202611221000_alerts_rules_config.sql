-- A's tables (spec §8), in the shape the API, processor, executor and delivery already use. Written by B with the
-- team's OK. Ids of runtime rows are bigint; config ids are slugs.

-- Rules: one JSON document per rule (spec §4); "when" is quoted because WHEN is an SQL keyword.
CREATE TABLE rules (
    id                 text PRIMARY KEY CHECK (id ~ '^[a-z0-9][a-z0-9_.-]*$'),
    owner              jsonb       NOT NULL,          -- {"team": "rates"} | {"user": "anna"}
    enabled            boolean     NOT NULL DEFAULT true,
    "when"             jsonb       NOT NULL,
    route              jsonb       NOT NULL DEFAULT '[]',
    present            jsonb       NOT NULL DEFAULT '{}',
    dedup              jsonb       NOT NULL DEFAULT '{}',
    auto_resolve_after interval,
    runbook_ids        text[]      NOT NULL DEFAULT '{}',
    updated_by         text        NOT NULL,
    updated_at         timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX rules_owner_team_idx ON rules ((owner->>'team'));

-- Bumped on every change of sources, mappings, rules, runbooks (by the writer, with NOTIFY config_changed).
CREATE TABLE config_version (
    singleton boolean PRIMARY KEY DEFAULT true CHECK (singleton),
    version   bigint  NOT NULL
);
INSERT INTO config_version (version) VALUES (1);

-- Sources (spec §2, §8). The HTTP ingest token is stored as a SHA-256 hash, never in clear (spec §11).
CREATE TABLE sources (
    id               text PRIMARY KEY CHECK (id ~ '^[a-z0-9][a-z0-9_.-]*$'),
    type             text        NOT NULL CHECK (type IN ('http', 'kafka', 'logfile')),
    config           jsonb       NOT NULL DEFAULT '{}',   -- kafka: {topic, group}; logfile: {path}
    parser           text        NOT NULL DEFAULT 'json' CHECK (parser IN ('json', 'logfmt', 'regex')),
    parser_config    jsonb       NOT NULL DEFAULT '{}',   -- regex: {"pattern": "..."}
    default_severity text        NOT NULL DEFAULT 'info' CHECK (default_severity IN ('info', 'warning', 'error', 'critical')),
    token_sha256     text,
    enabled          boolean     NOT NULL DEFAULT true,
    updated_by       text,
    updated_at       timestamptz NOT NULL DEFAULT now()
);

-- Schema mappings (spec §3, §8): lower priority number is tried first.
CREATE TABLE schema_mappings (
    id          text PRIMARY KEY CHECK (id ~ '^[a-z0-9][a-z0-9_.-]*$'),
    priority    integer     NOT NULL DEFAULT 100,
    source_ids  text[],                                 -- NULL = every source
    detect      jsonb,
    schema_from text,
    split_on    text,
    fields      jsonb       NOT NULL DEFAULT '{}',
    enabled     boolean     NOT NULL DEFAULT true,
    updated_by  text,
    updated_at  timestamptz NOT NULL DEFAULT now()
);

-- Idempotency of the processor (spec §5): inserted first in every batch; cleaned after 24 h by the scheduler.
CREATE TABLE processed_events (
    event_id     text PRIMARY KEY,
    processed_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX processed_events_processed_at_idx ON processed_events (processed_at);

-- Alerts (spec §5, §8). Exactly one open alert per fingerprint, enforced only by the partial unique index.
-- Defaults exist only so that tests of other modules can insert small rows; the processor sets every column.
CREATE TABLE alerts (
    id                 bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    rule_id            text,
    owner              jsonb       NOT NULL DEFAULT '{}',
    extra_teams        text[]      NOT NULL DEFAULT '{}',   -- teams added by the `escalate` action
    fingerprint        text        NOT NULL DEFAULT gen_random_uuid()::text,
    correlation_key    text,
    state              text        NOT NULL DEFAULT 'open' CHECK (state IN ('open', 'acknowledged', 'resolved')),
    severity           text        NOT NULL DEFAULT 'info' CHECK (severity IN ('info', 'warning', 'error', 'critical')),
    title              text        NOT NULL DEFAULT '',
    body               text,
    color              text,
    fields             jsonb       NOT NULL DEFAULT '[]',   -- present.fields paths at creation
    count              integer     NOT NULL DEFAULT 1 CHECK (count > 0),
    first_seen         timestamptz NOT NULL DEFAULT now(),
    last_seen          timestamptz NOT NULL DEFAULT now(),
    last_event_time    timestamptz NOT NULL DEFAULT now(),
    first_event        jsonb       NOT NULL DEFAULT '{}',
    last_event         jsonb       NOT NULL DEFAULT '{}',
    auto_resolve_after interval,
    acked_by           text,
    acked_at           timestamptz,
    resolved_by        text,
    resolved_at        timestamptz,
    resolved_how       text CHECK (resolved_how IN ('manual', 'event', 'runbook', 'silence')),
    previous_alert_id  bigint
);
CREATE UNIQUE INDEX alerts_open_fingerprint ON alerts (fingerprint) WHERE state <> 'resolved';
CREATE INDEX alerts_correlation_key_idx ON alerts (correlation_key) WHERE state <> 'resolved';
CREATE INDEX alerts_last_seen_idx ON alerts (last_seen DESC, id DESC);
CREATE INDEX alerts_owner_team_idx ON alerts ((owner->>'team'), last_seen DESC);
CREATE INDEX alerts_silence_idx ON alerts (last_seen) WHERE state <> 'resolved' AND auto_resolve_after IS NOT NULL;

-- "Niezmapowane" (spec §3): one row per key-set shape and source, with a count and the latest sample.
CREATE TABLE unmapped_samples (
    shape_hash text        NOT NULL,
    source_id  text        NOT NULL,
    sample     jsonb,
    count      integer     NOT NULL DEFAULT 1,
    first_seen timestamptz NOT NULL DEFAULT now(),
    last_seen  timestamptz NOT NULL DEFAULT now(),
    PRIMARY KEY (shape_hash, source_id)
);

-- Log tailer position per file (spec §2: one tailer per file, offset kept in Postgres).
CREATE TABLE tailer_offsets (
    source_id  text        NOT NULL,
    file       text        NOT NULL,
    inode      bigint,
    "offset"   bigint      NOT NULL DEFAULT 0,
    updated_at timestamptz NOT NULL DEFAULT now(),
    PRIMARY KEY (source_id, file)
);

-- "Propose fixes" (spec §8, §9 P3).
CREATE TABLE suggestions (
    id          bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    alert_id    bigint,
    target_type text        NOT NULL CHECK (target_type IN ('rule', 'runbook')),
    target_id   text        NOT NULL,
    text        text        NOT NULL,
    author      text        NOT NULL,
    status      text        NOT NULL DEFAULT 'open' CHECK (status IN ('open', 'accepted', 'rejected')),
    decided_by  text,
    created_at  timestamptz NOT NULL DEFAULT now(),
    decided_at  timestamptz
);
